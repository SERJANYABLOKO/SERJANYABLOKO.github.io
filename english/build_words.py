def parse(block):
    out = []
    for line in block.strip().splitlines():
        if '|' not in line: continue
        w, ru = line.split('|', 1)
        w, ru = w.strip(), ru.strip()
        if w and ru:
            out.append((w, ru))
    return out

words = []
seen = set()
per_cat = {}
for cat, block in groups.items():
    per_cat[cat] = 0
    for w, ru in parse(block):
        low = w.lower()
        if low in seen or per_cat[cat] >= 50: continue
        seen.add(low)
        per_cat[cat] += 1
        words.append({'word': w, 'ru': ru, 'cat': cat})

# Добираем до 1000 слов за счёт дополнительного пула глаголов
for w, ru in parse(extra):
    if len(words) >= 1000: break
    low = w.lower()
    if low in seen: continue
    seen.add(low)
    words.append({'word': w, 'ru': ru, 'cat': 'Глаголы'})

words = words[:1000]
